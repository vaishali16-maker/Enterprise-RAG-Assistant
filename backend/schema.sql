-- Enterprise RAG Assistant: base database schema (Supabase / PostgreSQL + pgvector)
--
-- Run this first on a new Supabase project (SQL Editor), then run the incremental
-- files in backend/migrations/ only if they are newer than this file. The tables,
-- search functions and security settings below already include everything those
-- migrations add.
--
-- Requires Supabase: it uses auth.users and the storage schema.

-- Extensions -------------------------------------------------------------------
create extension if not exists vector;

-- Tables -----------------------------------------------------------------------
create table if not exists tenants (
  id uuid primary key default gen_random_uuid(),
  name text not null unique,
  created_at timestamptz not null default now()
);

create table if not exists profiles (
  id uuid primary key references auth.users(id) on delete cascade,
  tenant_id uuid references tenants(id) on delete set null,
  full_name text,
  role text not null default 'employee'
    check (role in ('employee', 'manager', 'hr', 'admin')),
  created_at timestamptz not null default now()
);

create table if not exists documents (
  id uuid primary key default gen_random_uuid(),
  tenant_id uuid not null references tenants(id) on delete cascade,
  name text not null,
  allowed_roles text[] not null default array['employee', 'manager', 'hr', 'admin'],
  uploaded_by uuid references auth.users(id) on delete set null,
  created_at timestamptz not null default now()
);

create table if not exists chunks (
  id bigint generated by default as identity primary key,
  document_id uuid not null references documents(id) on delete cascade,
  chunk_index integer not null,
  content text not null,
  embedding vector(384) not null,
  page_number integer,
  suggested_questions jsonb not null default '[]'::jsonb
);

create table if not exists entities (
  id bigint generated by default as identity primary key,
  document_id uuid not null references documents(id) on delete cascade,
  name text not null,
  type text
);

create table if not exists relations (
  id bigint generated by default as identity primary key,
  document_id uuid not null references documents(id) on delete cascade,
  source_entity_id bigint not null references entities(id) on delete cascade,
  target_entity_id bigint not null references entities(id) on delete cascade,
  relation text not null
);

create table if not exists conversations (
  id uuid primary key default gen_random_uuid(),
  user_id uuid not null references auth.users(id) on delete cascade,
  title text not null default 'New conversation',
  created_at timestamptz not null default now()
);

create table if not exists messages (
  id bigint generated by default as identity primary key,
  conversation_id uuid not null references conversations(id) on delete cascade,
  role text not null check (role in ('user', 'assistant')),
  content text not null,
  sources jsonb,
  created_at timestamptz not null default now(),
  follow_up_questions jsonb default '[]'::jsonb,
  low_confidence boolean default false,
  top_similarity double precision
);

create table if not exists message_feedback (
  message_id text primary key,
  user_id uuid not null references auth.users(id) on delete cascade,
  rating text not null check (rating in ('helpful', 'not_helpful')),
  created_at timestamptz not null default now()
);

create table if not exists query_cache (
  id bigint generated by default as identity primary key,
  tenant_id uuid not null references tenants(id) on delete cascade,
  question text not null,
  embedding vector(384) not null,
  answer text not null,
  sources jsonb,
  created_at timestamptz not null default now(),
  role text not null
);

create table if not exists request_log (
  id bigint generated by default as identity primary key,
  tenant_id uuid,
  user_id uuid,
  question text,
  cache_hit boolean not null,
  model text,
  latency_ms integer,
  created_at timestamptz not null default now()
);

create table if not exists document_audit_log (
  id bigint generated by default as identity primary key,
  tenant_id uuid not null,
  document_id uuid not null,
  document_name text not null,
  action text not null check (action in ('upload', 'delete', 'access_change')),
  actor_id uuid not null,
  actor_role text not null check (actor_role in ('admin', 'hr', 'manager')),
  old_allowed_roles jsonb,
  new_allowed_roles jsonb,
  created_at timestamptz not null default now()
);

-- Indexes ----------------------------------------------------------------------
create index if not exists chunks_document_idx on chunks (document_id);
create index if not exists chunks_document_page_idx on chunks (document_id, page_number);
create index if not exists chunks_embedding_idx on chunks using hnsw (embedding vector_cosine_ops);
create index if not exists chunks_content_english_fts_idx
  on chunks using gin (to_tsvector('english'::regconfig, coalesce(content, ''::text)));
create index if not exists documents_tenant_idx on documents (tenant_id);
create index if not exists query_cache_embedding_idx on query_cache using hnsw (embedding vector_cosine_ops);
create index if not exists document_audit_log_document_idx on document_audit_log (document_id, created_at desc);
create index if not exists document_audit_log_tenant_created_idx on document_audit_log (tenant_id, created_at desc);

-- Search functions -------------------------------------------------------------
-- Vector search. Role filtering happens here: a chunk is returned only if the
-- caller's role is listed in the document's allowed_roles.
create or replace function match_chunks(
  query_embedding vector,
  match_threshold double precision,
  match_count integer,
  p_tenant_id uuid,
  p_role text
)
returns table (
  id bigint,
  document_id uuid,
  document_name text,
  chunk_index integer,
  content text,
  similarity double precision
)
language sql
stable
as $function$
  select c.id, c.document_id, d.name, c.chunk_index, c.content,
         1 - (c.embedding <=> query_embedding) as similarity
  from chunks c
  join documents d on d.id = c.document_id
  where d.tenant_id = p_tenant_id
    and p_role = any (d.allowed_roles)
    and 1 - (c.embedding <=> query_embedding) > match_threshold
  order by c.embedding <=> query_embedding
  limit match_count;
$function$;

-- Keyword (full-text) search, scoped by tenant, role and optional document list.
create or replace function search_chunks_lexical(
  p_query text,
  p_tenant_id uuid,
  p_role text,
  p_document_ids uuid[] default null::uuid[],
  p_match_count integer default 12
)
returns table (
  document_id uuid,
  chunk_index integer,
  page_number integer,
  document_name text,
  content text,
  suggested_questions jsonb,
  lexical_score real
)
language sql
stable
set search_path to 'public'
as $function$
  with parsed_query as (
    select websearch_to_tsquery('english', p_query) as query
  )
  select
    c.document_id,
    c.chunk_index,
    c.page_number,
    d.name as document_name,
    c.content,
    c.suggested_questions,
    ts_rank_cd(to_tsvector('english', coalesce(c.content, '')), parsed_query.query)::real as lexical_score
  from public.chunks c
  join public.documents d on d.id = c.document_id
  cross join parsed_query
  where d.tenant_id = p_tenant_id
    and (coalesce(jsonb_array_length(to_jsonb(d.allowed_roles)), 0) = 0 or to_jsonb(d.allowed_roles) ? p_role)
    and (p_document_ids is null or c.document_id = any(p_document_ids))
    and to_tsvector('english', coalesce(c.content, '')) @@ parsed_query.query
  order by lexical_score desc
  limit greatest(1, least(p_match_count, 100));
$function$;

-- Semantic cache lookup, scoped by tenant and role so answers never cross roles.
create or replace function match_cached_query(
  query_embedding vector,
  p_tenant_id uuid,
  p_role text,
  match_threshold double precision default 0.95
)
returns table (answer text, sources jsonb, similarity double precision)
language sql
stable
set search_path to 'public'
as $function$
    select
        cache.answer,
        cache.sources,
        (1 - (cache.embedding <=> query_embedding))::double precision as similarity
    from public.query_cache as cache
    where cache.tenant_id = p_tenant_id
      and cache.role = p_role
      and cache.embedding is not null
      and 1 - (cache.embedding <=> query_embedding) >= match_threshold
    order by cache.embedding <=> query_embedding
    limit 1;
$function$;

-- New-user profile --------------------------------------------------------------
-- Every new auth user gets an employee profile in the "Demo Company" tenant.
-- Promote users by updating profiles.role.
create or replace function handle_new_user()
returns trigger
language plpgsql
security definer
set search_path to 'public'
as $function$
begin
  insert into public.profiles (id, tenant_id, full_name, role)
  values (
    new.id,
    (select id from public.tenants where name = 'Demo Company' limit 1),
    new.raw_user_meta_data ->> 'full_name',
    'employee'
  );
  return new;
end;
$function$;

drop trigger if exists on_auth_user_created on auth.users;
create trigger on_auth_user_created
  after insert on auth.users
  for each row execute function handle_new_user();

insert into tenants (name) values ('Demo Company') on conflict (name) do nothing;

-- Security ---------------------------------------------------------------------
-- Row-level security on every table with no policies: only the backend (service
-- role) can read or write. The public (anon) key cannot query any table directly.
alter table tenants enable row level security;
alter table profiles enable row level security;
alter table documents enable row level security;
alter table chunks enable row level security;
alter table entities enable row level security;
alter table relations enable row level security;
alter table conversations enable row level security;
alter table messages enable row level security;
alter table message_feedback enable row level security;
alter table query_cache enable row level security;
alter table request_log enable row level security;
alter table document_audit_log enable row level security;

revoke all on table document_audit_log from anon, authenticated;

-- The search functions are meant for the backend only.
revoke execute on function match_chunks(vector, double precision, integer, uuid, text) from public, anon, authenticated;
revoke execute on function search_chunks_lexical(text, uuid, text, uuid[], integer) from public, anon, authenticated;
revoke execute on function match_cached_query(vector, uuid, text, double precision) from public, anon, authenticated;
grant execute on function match_chunks(vector, double precision, integer, uuid, text) to service_role;
grant execute on function search_chunks_lexical(text, uuid, text, uuid[], integer) to service_role;
grant execute on function match_cached_query(vector, uuid, text, double precision) to service_role;

