-- Record who uploaded each document and retain an audit trail for management actions.
ALTER TABLE public.documents
    ADD COLUMN IF NOT EXISTS uploaded_by uuid;

CREATE TABLE IF NOT EXISTS public.document_audit_log (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    tenant_id uuid NOT NULL,
    document_id uuid NOT NULL,
    document_name text NOT NULL,
    action text NOT NULL CHECK (action IN ('upload', 'delete', 'access_change')),
    actor_id uuid NOT NULL,
    actor_role text NOT NULL CHECK (actor_role IN ('admin', 'hr', 'manager')),
    old_allowed_roles jsonb,
    new_allowed_roles jsonb,
    created_at timestamptz NOT NULL DEFAULT now()
);

CREATE INDEX IF NOT EXISTS document_audit_log_tenant_created_idx
    ON public.document_audit_log (tenant_id, created_at DESC);
CREATE INDEX IF NOT EXISTS document_audit_log_document_idx
    ON public.document_audit_log (document_id, created_at DESC);

ALTER TABLE public.document_audit_log ENABLE ROW LEVEL SECURITY;
REVOKE ALL ON public.document_audit_log FROM anon, authenticated;
GRANT ALL ON public.document_audit_log TO service_role;
GRANT USAGE, SELECT ON SEQUENCE public.document_audit_log_id_seq TO service_role;
